-- Rode no SQL Editor do Supabase antes de subir o backend novo.
-- Equipe do studio: cada profissional entra no painel com a conta Google,
-- atende os serviços vinculados a ela e tem a própria agenda de horários.
-- O cadastro da proprietária (ADMIN_EMAIL) é criado pelo backend no primeiro uso,
-- já com todos os serviços e com os agendamentos antigos.

create table if not exists public.profissionais (
  id integer generated by default as identity primary key,
  nome text not null,
  email text not null,
  proprietaria boolean not null default false,
  -- Removida pela proprietária: some das listas, mas o histórico de agendamentos fica
  ativo boolean not null default true,
  -- Acesso à Agenda Google dela, salvo no login (só o backend lê esta tabela)
  google_refresh_token text,
  criado_em timestamptz not null default now()
);

create unique index if not exists profissionais_email_unico on public.profissionais (lower(email));
create unique index if not exists profissionais_uma_proprietaria on public.profissionais (proprietaria) where proprietaria;
alter table public.profissionais enable row level security;

-- Serviços que cada profissional realiza
create table if not exists public.profissionais_servicos (
  profissional_id integer not null references public.profissionais (id) on delete cascade,
  servico_id integer not null references public.servicos (id) on delete cascade,
  primary key (profissional_id, servico_id)
);
alter table public.profissionais_servicos enable row level security;

alter table public.agendamentos
  add column if not exists profissional_id integer references public.profissionais (id);
-- true: o evento está na Agenda Google da profissional; false: na agenda da proprietária
alter table public.agendamentos
  add column if not exists evento_agenda_propria boolean not null default false;

-- Duas profissionais podem atender no mesmo horário; a mesma profissional, não
drop index if exists public.agendamentos_horario_unico;
create unique index if not exists agendamentos_horario_profissional_unico
  on public.agendamentos (profissional_id, data_hora)
  where status is distinct from 'cancelado';
